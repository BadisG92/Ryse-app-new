  static Path _decode(String data, double scale) {
    // Even-odd, so the counter of the R and of the e stay holes instead of
    // being flooded with the letter.
    final path = Path()..fillType = PathFillType.evenOdd;
    final v = data.split(',');
    var i = 0;
    double n() => double.parse(v[i++]) * scale;
    while (i < v.length) {
      switch (v[i++]) {
        case '0':
          path.moveTo(n(), n());
        case '1':
          path.lineTo(n(), n());
        case '2':
          path.cubicTo(n(), n(), n(), n(), n(), n());
        default:
          path.close();
      }
    }
    return path;
  }

  /// The mark: the dot, then the swoosh.
  static List<Path> icon(double width) => [_decode(_icon0, width), _decode(_icon1, width)];

  /// R, y, z, e — in the order a hand would write them.
  static List<Path> letters(double width) =>
      [_decode(_letter0, width), _decode(_letter1, width), _decode(_letter2, width), _decode(_letter3, width)];

  /// Where the opening grows from: the thickest point of the swoosh, found by
  /// searching the shape for the point furthest from any edge. The bounding
  /// box centre falls in the gap between the dot and the swoosh, so a mark
  /// blown up from there opens onto a hollow and never covers the screen.
  static Offset markAnchor(double width) => Offset(0.4586 * width, 0.4382 * width);

  /// Radius of the largest disc that fits inside the swoosh at that anchor.
  /// Scale the mark by `distance / (anchorRadius)` and the screen is covered.
  static double anchorRadius(double width) => 0.094 * width;
